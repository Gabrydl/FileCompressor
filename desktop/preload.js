// The only bridge between the page and the computer.
const { contextBridge, ipcRenderer, webUtils } = require("electron");
contextBridge.exposeInMainWorld("Desktop", {
  pickFiles: () => ipcRenderer.invoke("pick-files"),
  pickFolder: () => ipcRenderer.invoke("pick-folder"),
  expand: (paths) => ipcRenderer.invoke("expand", paths),
  pathOf: (file) => { try { return webUtils.getPathForFile(file) || ""; } catch (_) { return ""; } },
  defaultOutDir: () => ipcRenderer.sendSync("default-out"),
  chooseOutDir: (current) => ipcRenderer.invoke("choose-out", current),
  start: (items, settings) => ipcRenderer.send("start", items, settings),
  abort: () => ipcRenderer.send("abort"),
  progress: (f) => ipcRenderer.send("progress", f),
  onItem: (cb) => ipcRenderer.on("item", (_e, d) => cb(d)),
  onFinished: (cb) => ipcRenderer.on("finished", (_e, d) => cb(d)),
  onNote: (cb) => ipcRenderer.on("note", (_e, t) => cb(t)),
  onOpen: (cb) => ipcRenderer.on("open-paths", (_e, p) => cb(p)),
  openPath: (p) => ipcRenderer.send("open-path", p),
  showItem: (p) => ipcRenderer.send("show-item", p),
  openFolder: (p) => ipcRenderer.send("open-folder", p),
  setTheme: (t, dark) => ipcRenderer.send("set-theme", t, dark),
  ready: () => ipcRenderer.send("ready"),
  // 1.5.0
  inspect: (list) => ipcRenderer.invoke("inspect", list),
  preview: (it, page) => ipcRenderer.invoke("preview", it, page),
  reviewSave: (it, s) => ipcRenderer.invoke("review-save", it, s),
  reviewDiscard: (held) => ipcRenderer.invoke("review-discard", held),
  history: () => ipcRenderer.invoke("history"),
  historyClear: () => ipcRenderer.invoke("history-clear"),
  restore: (entry, removeCopy) => ipcRenderer.invoke("restore", entry, removeCopy),
  paste: () => ipcRenderer.invoke("paste"),
  startDrag: (file) => ipcRenderer.send("start-drag", file),
  notify: (title, body, folder) => ipcRenderer.send("notify", title, body, folder),
  focused: () => ipcRenderer.sendSync("focused"),
  explorerMenu: (on) => ipcRenderer.invoke("explorer-menu", on),
  // 1.8.0: languages and the log file
  lang: () => ipcRenderer.sendSync("lang-get"),
  setLang: (c) => ipcRenderer.sendSync("lang-set", c),
  log: (level, msg) => ipcRenderer.send("log", level, String(msg)),
  openLog: () => ipcRenderer.send("open-log"),
});
